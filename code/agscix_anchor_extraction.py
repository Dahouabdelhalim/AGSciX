import re
import os

def extract_entity_context(entity, file_path):
    if not os.path.exists(file_path):
        return "File not found."

    with open(file_path, 'r', encoding='utf-8') as f:
        content = f.read()

    # Find the first occurrence of the entity
    # Use re.escape to handle special characters in the entity name
    match = re.search(re.escape(entity), content)

    if not match:
        return f"Entity '{entity}' not found in the file."

    start_idx, end_idx = match.span()

    # --- Extract Left Context ---
    # Find the start of the "passage" (defined here as the start of the file
    # or the nearest previous newline)
    passage_start = content.rfind('\n', 0, start_idx)
    if passage_start == -1:
        passage_start = 0
    else:
        passage_start += 1  # Move past the newline character

    left_context = content[passage_start:start_idx]

    # --- Extract Right Context ---
    # Find the first period or newline after the entity
    # We look for the first occurrence of '.' or '\n'
    right_search_area = content[end_idx:]
    end_match = re.search(r'[.\n]', right_search_area)

    if end_match:
        # Include the punctuation in the right context
        right_context = right_search_area[:end_match.start() + 1]
    else:
        # If no punctuation found, take the rest of the file
        right_context = right_search_area

    return {
        "entity": entity,
        "left_context": left_context.strip(),
        "right_context": right_context.strip(),
        "full_passage": (left_context + entity + right_context).strip()
    }

# Example Usage:
result = extract_entity_context("Ansgar Scherp", "/content/12- 2501.13598v1.md")
print(f"Left: {result}")
print(f"Right: {result}")

