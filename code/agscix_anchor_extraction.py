def get_string_span(file_path, search_string):
    try:
        with open(file_path, 'r', encoding='utf-8') as f:
            content = f.read()

        # Find the starting character index
        start_index = content.find(search_string)

        if start_index == -1:
            return None, "String not found in file."

        # Calculate the end index
        end_index = start_index + len(search_string)

        return (start_index, end_index), None

    except FileNotFoundError:
        return None, "File not found."

