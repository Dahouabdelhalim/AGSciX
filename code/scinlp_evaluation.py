import json
import os
from typing import List, Dict, Any

def load_json_multiple(file_path: str) -> List[Dict[str, Any]]:
    """
    Load a JSON file that may contain either:
      - a single JSON object
      - a single JSON array
      - multiple concatenated JSON objects (e.g., NDJSON)
    Returns a list of document dictionaries.
    """
    with open(file_path, 'r', encoding='utf-8') as f:
        content = f.read().strip()

    # Try parsing as a single JSON value first
    try:
        data = json.loads(content)
        if isinstance(data, list):
            return data
        else:
            return [data]
    except json.JSONDecodeError as e:
        if "Extra data" in str(e):
            decoder = json.JSONDecoder()
            objects = []
            idx = 0
            content_len = len(content)
            while idx < content_len:
                try:
                    obj, idx = decoder.raw_decode(content, idx)
                    objects.append(obj)
                    while idx < content_len and content[idx] in ' \t\n\r':
                        idx += 1
                except json.JSONDecodeError:
                    break
            if objects:
                return objects
            else:
                raise
        else:
            raise

def save_documents_sentences_only(input_json_path: str, output_dir: str):
    """
    Reads the input JSON, extracts each document's doc_key and sentences,
    and saves them as separate JSON files in output_dir.
    """
    # Create output directory if it doesn't exist
    os.makedirs(output_dir, exist_ok=True)

    # Load all documents
    documents = load_json_multiple(input_json_path)

    for doc in documents:
        doc_key = doc.get("doc_key", "unknown")
        sentences = doc.get("sentences", [])

        # Build the minimal output dictionary
        output_data = {
            "doc_key": doc_key,
            "sentences": sentences
        }

        # Create a safe filename (replace slashes, etc.)
        safe_filename = str(doc_key).replace('/', '_').replace('\\', '_')
        output_path = os.path.join(output_dir, f"{safe_filename}.json")

        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(output_data, f, indent=2, ensure_ascii=False)

        print(f"Saved: {output_path}")

