def main():
    GROUND_TRUTH_CSV = 'All NER Entities GSAP Test Set.csv'
    PREDICTION_FOLDER = './predictions_csv_hard/'   # folder containing the 10 prediction CSV files
    # Alternatively, provide a list of file paths manually:
    # prediction_files = ['pred1.csv', 'pred2.csv', ...]

    # Automatically find all CSV files in the folder (excluding ground truth)
    all_csv_files = glob.glob(os.path.join(PREDICTION_FOLDER, '*.csv'))
    # Optional: filter out the ground truth file if it happens to be in the same folder
    prediction_files = [f for f in all_csv_files if os.path.basename(f) != os.path.basename(GROUND_TRUTH_CSV)]

    if not prediction_files:
        print(f"No prediction CSV files found in {PREDICTION_FOLDER}")
        return

    print(f"Found {len(prediction_files)} prediction CSV files.")

    # Load ground truth
    true_by_doc = load_ground_truth_by_doc(GROUND_TRUTH_CSV)
    doc_ids = list(true_by_doc.keys())
    print(f"Ground truth contains {len(doc_ids)} documents.")

    # Load and merge all predictions
    merged_pred_by_doc = load_and_merge_predictions(prediction_files)

    # Optional: deduplicate predictions per document (in case of overlapping spans from multiple files)
    for doc_id in merged_pred_by_doc:
        merged_pred_by_doc[doc_id] = deduplicate_predictions(merged_pred_by_doc[doc_id])

    print(f"After merging, predictions cover {len(merged_pred_by_doc)} documents.")

    # Evaluate per document (only those with ground truth)
    per_doc_results = []
    for doc_id in doc_ids:
        print(f"\n--- {doc_id} ---")
        true_entities = true_by_doc[doc_id]
        pred_entities = merged_pred_by_doc.get(doc_id, [])
        print(f"  Ground truth: {len(true_entities)} | Predictions: {len(pred_entities)}")

        res = evaluate_document(true_entities, pred_entities)
        per_doc_results.append((doc_id, res))
        print(f"  Exact F1: {res['exact']['f1']:.3f}   Partial F1 (micro): {res['partial']['f1']:.3f}   Partial Macro F1 (over true labels): {res['partial']['macro_f1']:.3f}")

    # Global aggregation across all documents
    label_stats, macro_f1_exact, macro_f1_partial = aggregate_across_documents(true_by_doc, merged_pred_by_doc)

    print("\n" + "="*60)
    print("PER-LABEL PERFORMANCE (all documents)")
    print("="*60)
    for label in ALLOWED_LABELS:
        s = label_stats[label]
        print(f"{label:18s} Exact: P={s['exact']['precision']:.3f} R={s['exact']['recall']:.3f} F1={s['exact']['f1']:.3f}   Partial: P={s['partial']['precision']:.3f} R={s['partial']['recall']:.3f} F1={s['partial']['f1']:.3f}")

    print("\n" + "="*60)
    print("MACRO-AVERAGE OVER CLASSES")
    print("="*60)
    print(f"Exact Macro-F1:   {macro_f1_exact:.4f}")
    print(f"Partial Macro-F1: {macro_f1_partial:.4f}")

    # Micro averages
    total_tp_exact = sum(r['counts']['tp_exact'] for _, r in per_doc_results)
    total_fp_exact = sum(r['counts']['fp_exact'] for _, r in per_doc_results)
    total_fn_exact = sum(r['counts']['fn_exact'] for _, r in per_doc_results)
    total_tp_partial = sum(r['counts']['tp_partial'] for _, r in per_doc_results)
    total_fp_partial = sum(r['counts']['fp_partial'] for _, r in per_doc_results)
    total_fn_partial = sum(r['counts']['fn_partial'] for _, r in per_doc_results)

    prec_exact_micro = total_tp_exact / (total_tp_exact + total_fp_exact) if (total_tp_exact + total_fp_exact) > 0 else 0
    rec_exact_micro = total_tp_exact / (total_tp_exact + total_fn_exact) if (total_tp_exact + total_fn_exact) > 0 else 0
    f1_exact_micro = 2 * prec_exact_micro * rec_exact_micro / (prec_exact_micro + rec_exact_micro) if (prec_exact_micro + rec_exact_micro) > 0 else 0
    prec_partial_micro = total_tp_partial / (total_tp_partial + total_fp_partial) if (total_tp_partial + total_fp_partial) > 0 else 0
    rec_partial_micro = total_tp_partial / (total_tp_partial + total_fn_partial) if (total_tp_partial + total_fn_partial) > 0 else 0
    f1_partial_micro = 2 * prec_partial_micro * rec_partial_micro / (prec_partial_micro + rec_partial_micro) if (prec_partial_micro + rec_partial_micro) > 0 else 0

    print("\n" + "="*60)
    print("MICRO-AVERAGE (across documents and classes)")
    print("="*60)
    print(f"Exact   - P={prec_exact_micro:.4f} R={rec_exact_micro:.4f} F1={f1_exact_micro:.4f}")
    print(f"Partial - P={prec_partial_micro:.4f} R={rec_partial_micro:.4f} F1={f1_partial_micro:.4f}")


if __name__ == '__main__':
    main()

