def normalize_doc_id(doc_id):
    """Normalize doc_id: remove .txt extension and any path."""
    base = os.path.basename(doc_id)
    if base.endswith('.txt'):
        base = base[:-4]
    return base

def load_ground_truth_by_doc(csv_path):
    true_by_doc = defaultdict(list)
    with open(csv_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            label = row['ner_label']
            if label in ALLOWED_LABELS:
                doc_id = normalize_doc_id(row['doc_id'])
                true_by_doc[doc_id].append({
                    'start': int(row['start_char']),
                    'end': int(row['end_char']),
                    'label': label,
                    'text': row.get('text', '')
                })
    return true_by_doc

def load_predictions_by_doc(csv_path):
    pred_by_doc = defaultdict(list)
    with open(csv_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            label = row['ner_label']
            if label in ALLOWED_LABELS:
                doc_id = normalize_doc_id(row['doc_id'])
                pred_by_doc[doc_id].append({
                    'start': int(row['start_char']),
                    'end': int(row['end_char']),
                    'label': label,
                    'text': row.get('text', '')
                })
    return pred_by_doc

