# 3. Load and merge multiple prediction CSV files
# ----------------------------------------------------------------------
def load_and_merge_predictions(csv_files):
    """Load predictions from several CSV files and return a single dict.
       If a doc_id appears in multiple files, all entities are combined."""
    merged_pred_by_doc = defaultdict(list)
    for file_path in csv_files:
        print(f"  Loading predictions from: {os.path.basename(file_path)}")
        pred_by_doc = load_predictions_by_doc(file_path)
        for doc_id, entities in pred_by_doc.items():
            merged_pred_by_doc[doc_id].extend(entities)
    return merged_pred_by_doc


# ----------------------------------------------------------------------
# 4. Deduplicate predictions per document (exact same start/end/label)
# ----------------------------------------------------------------------
def deduplicate_predictions(pred_entities):
    seen = set()
    unique = []
    for ent in pred_entities:
        key = (ent['start'], ent['end'], ent['label'])
        if key not in seen:
            seen.add(key)
            unique.append(ent)
    return unique


