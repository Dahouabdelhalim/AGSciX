import json
import csv
import os

ALLOWED_LABELS = {'Method', 'Task', 'DataSource', 'Dataset', 'MLModel', 'ModelArchitecture'}

def load_ground_truth(csv_path):
    """Load GSAP CSV and keep only allowed labels."""
    true_entities = []
    with open(csv_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            label = row['ner_label']
            if label in ALLOWED_LABELS:
                true_entities.append({
                    'doc_id': row['doc_id'],
                    'start': int(row['start_char']),
                    'end': int(row['end_char']),
                    'label': label,
                    'text': row['text']
                })
    return true_entities

"""**2 - Load document raw text (for extracting spans)**"""

def load_document_text(doc_id, doc_folder):
    """Load raw text from .txt file named exactly as doc_id (e.g., 00001_1911_02116.txt)."""
    file_path = os.path.join(doc_folder, doc_id)
    with open(file_path, 'r', encoding='utf-8') as f:
        return f.read()

"""**3 - Flatten JSON‑LD predictions**"""

def map_type_to_gsap(typed_entity):
    """
    Map JSON-LD @type(s) to GSAP allowed labels.
    Allowed outputs: Method, Task, DataSource, Dataset, MLModel, ModelArchitecture.
    Returns None for other types.
    """
    types = typed_entity.get('@type', [])
    if isinstance(types, str):
        types = [types]

    # Map specific types to labels
    if 'Method' in types or 'MLS_Algorithm' in types:
        return 'Method'
    if 'MLS_Task' in types:
        return 'Task'
    if 'DataSource' in types:
        return 'DataSource'
    if 'MLS_Dataset' in types:
        return 'Dataset'
    if 'MLS_Model' in types:
        return 'MLModel'
    # Note: ModelArchitecture is handled separately in flatten_jsonld,
    # not from @type, but we keep it in ALLOWED_LABELS.
    return None


def flatten_jsonld(jsonld_path, doc_folder, doc_id=None):
    """
    Extract entities from JSON-LD @graph.
    Returns list of predicted entities (doc_id, start, end, label, text)
    using direct character offsets from:
      - 'mention' (for the main entity)
      - 'schema:architecture' or 'mls:architecture' (for architecture mentions)
    """
    with open(jsonld_path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    graph = data.get('@graph', [])
    predicted = []

    # If doc_id not provided, infer from file name (without extension)
    if doc_id is None:
        doc_id = os.path.splitext(os.path.basename(jsonld_path))[0] + '.txt'

    # Load document text once
    try:
        doc_text = load_document_text(doc_id, doc_folder)
    except FileNotFoundError:
        print(f"Warning: Document text not found for {doc_id}. Using mention.value as fallback.")
        doc_text = None

    for obj in graph:
        # --- Main entity from 'mention' ---
        if 'mention' in obj:
            mention = obj['mention']
            if 'start_char_doc' in mention and 'end_char_doc' in mention:
                start = mention['start_char_doc']
                end = mention['end_char_doc']
                if start is not None and end is not None:
                    if doc_text is not None:
                        extracted = doc_text[start:end]
                    else:
                        extracted = mention.get('value', '')
                    label = map_type_to_gsap(obj)
                    if label is not None:
                        predicted.append({
                            'doc_id': doc_id,
                            'start': start,
                            'end': end,
                            'label': label,
                            'text': extracted
                        })

        # --- Also check 'occurrences' for other annotations ---
        if 'occurrences' in obj and isinstance(obj['occurrences'], list):
            for occ in obj['occurrences']:
                if len(occ) >= 2 and isinstance(occ[0], int) and isinstance(occ[1], int):
                    start, end = occ[0], occ[1]
                    if doc_text is not None:
                        extracted = doc_text[start:end]
                    else:
                        extracted = ''
                    label = map_type_to_gsap(obj)
                    if label is not None:
                        predicted.append({
                            'doc_id': doc_id,
                            'start': start,
                            'end': end,
                            'label': label,
                            'text': extracted
                        })

        # --- Extract architecture from 'schema:architecture' OR 'mls:architecture' ---
        arch_key = None
        if 'schema:architecture' in obj:
            arch_key = 'schema:architecture'
        elif 'mls:architecture' in obj:
            arch_key = 'mls:architecture'

        if arch_key:
            arch = obj[arch_key]
            if isinstance(arch, dict):
                start = arch.get('start_char_doc')
                end = arch.get('end_char_doc')
                if start is not None and end is not None:
                    if doc_text is not None:
                        arch_text = doc_text[start:end]
                    else:
                        arch_text = arch.get('value', '')
                    predicted.append({
                        'doc_id': doc_id,
                        'start': start,
                        'end': end,
                        'label': 'ModelArchitecture',
                        'text': arch_text
                    })
            elif isinstance(arch, str):
                # If no character offsets, skip (we cannot reliably locate it)
                pass

    return predicted




