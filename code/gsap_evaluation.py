def evaluate_document(true_entities, pred_entities):
    pred_entities = [e for e in pred_entities if e['label'] in ALLOWED_LABELS]
    true_set_exact = {(e['start'], e['end'], e['label']) for e in true_entities}
    pred_set_exact = {(e['start'], e['end'], e['label']) for e in pred_entities}
    tp_exact = len(true_set_exact & pred_set_exact)
    fp_exact = len(pred_set_exact - true_set_exact)
    fn_exact = len(true_set_exact - pred_set_exact)

    true_by_label, pred_by_label = defaultdict(list), defaultdict(list)
    for e in true_entities:
        true_by_label[e['label']].append((e['start'], e['end']))
    for e in pred_entities:
        pred_by_label[e['label']].append((e['start'], e['end']))

    total_tp_partial, total_fp_partial, total_fn_partial = 0, 0, 0
    label_f1_partial = []

    for label in true_by_label.keys():
        true_spans = true_by_label.get(label, [])
        pred_spans = pred_by_label.get(label, [])
        used_true = [False] * len(true_spans)
        tp_l = 0
        for p_start, p_end in pred_spans:
            for i, (t_start, t_end) in enumerate(true_spans):
                if not used_true[i] and max(p_start, t_start) < min(p_end, t_end):
                    used_true[i] = True
                    tp_l += 1
                    break
        fp_l = len(pred_spans) - tp_l
        fn_l = len(true_spans) - sum(used_true)
        total_tp_partial += tp_l
        total_fp_partial += fp_l
        total_fn_partial += fn_l

        prec_l = tp_l / (tp_l + fp_l) if (tp_l + fp_l) > 0 else 0
        rec_l = tp_l / (tp_l + fn_l) if (tp_l + fn_l) > 0 else 0
        f1_l = 2 * prec_l * rec_l / (prec_l + rec_l) if (prec_l + rec_l) > 0 else 0
        label_f1_partial.append(f1_l)

    macro_f1_partial = sum(label_f1_partial) / len(label_f1_partial) if label_f1_partial else 0

    prec_partial = total_tp_partial / (total_tp_partial + total_fp_partial) if (total_tp_partial + total_fp_partial) > 0 else 0
    rec_partial = total_tp_partial / (total_tp_partial + total_fn_partial) if (total_tp_partial + total_fn_partial) > 0 else 0
    f1_partial = 2 * prec_partial * rec_partial / (prec_partial + rec_partial) if (prec_partial + rec_partial) > 0 else 0

    prec_exact = tp_exact / (tp_exact + fp_exact) if (tp_exact + fp_exact) > 0 else 0
    rec_exact = tp_exact / (tp_exact + fn_exact) if (tp_exact + fn_exact) > 0 else 0
    f1_exact = 2 * prec_exact * rec_exact / (prec_exact + rec_exact) if (prec_exact + rec_exact) > 0 else 0

    return {
        'exact': {'precision': prec_exact, 'recall': rec_exact, 'f1': f1_exact},
        'partial': {'precision': prec_partial, 'recall': rec_partial, 'f1': f1_partial, 'macro_f1': macro_f1_partial},
        'counts': {
            'tp_exact': tp_exact, 'fp_exact': fp_exact, 'fn_exact': fn_exact,
            'tp_partial': total_tp_partial, 'fp_partial': total_fp_partial, 'fn_partial': total_fn_partial
        }
    }


def aggregate_across_documents(all_true_by_doc, all_pred_by_doc):
    true_exact_by_label, pred_exact_by_label = defaultdict(set), defaultdict(set)
    true_spans_by_label, pred_spans_by_label = defaultdict(list), defaultdict(list)
    for doc_id in all_true_by_doc:
        for e in all_true_by_doc[doc_id]:
            label = e['label']
            span = (e['start'], e['end'])
            true_exact_by_label[label].add((span[0], span[1], label))
            true_spans_by_label[label].append(span)
        for e in all_pred_by_doc.get(doc_id, []):
            label = e['label']
            span = (e['start'], e['end'])
            pred_exact_by_label[label].add((span[0], span[1], label))
            pred_spans_by_label[label].append(span)

    label_stats = {}
    for label in ALLOWED_LABELS:
        # exact
        true_set = true_exact_by_label.get(label, set())
        pred_set = pred_exact_by_label.get(label, set())
        tp_exact = len(true_set & pred_set)
        fp_exact = len(pred_set - true_set)
        fn_exact = len(true_set - pred_set)
        prec_exact = tp_exact / (tp_exact + fp_exact) if (tp_exact + fp_exact) > 0 else 0
        rec_exact = tp_exact / (tp_exact + fn_exact) if (tp_exact + fn_exact) > 0 else 0
        f1_exact = 2 * prec_exact * rec_exact / (prec_exact + rec_exact) if (prec_exact + rec_exact) > 0 else 0
        # partial
        true_spans = true_spans_by_label.get(label, [])
        pred_spans = pred_spans_by_label.get(label, [])
        used_true = [False] * len(true_spans)
        tp_partial = 0
        for p_start, p_end in pred_spans:
            for i, (t_start, t_end) in enumerate(true_spans):
                if not used_true[i] and max(p_start, t_start) < min(p_end, t_end):
                    used_true[i] = True
                    tp_partial += 1
                    break
        fp_partial = len(pred_spans) - tp_partial
        fn_partial = len(true_spans) - sum(used_true)
        prec_partial = tp_partial / (tp_partial + fp_partial) if (tp_partial + fp_partial) > 0 else 0
        rec_partial = tp_partial / (tp_partial + fn_partial) if (tp_partial + fn_partial) > 0 else 0
        f1_partial = 2 * prec_partial * rec_partial / (prec_partial + rec_partial) if (prec_partial + rec_partial) > 0 else 0
        label_stats[label] = {'exact': {'precision': prec_exact, 'recall': rec_exact, 'f1': f1_exact},
                              'partial': {'precision': prec_partial, 'recall': rec_partial, 'f1': f1_partial}}
    macro_f1_exact = sum(stats['exact']['f1'] for stats in label_stats.values()) / len(ALLOWED_LABELS)
    macro_f1_partial = sum(stats['partial']['f1'] for stats in label_stats.values()) / len(ALLOWED_LABELS)
    return label_stats, macro_f1_exact, macro_f1_partial


